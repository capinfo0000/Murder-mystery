// 事件の時間帯トークン（T1/T2/T3）を自然な日本語表現に変換する。
// T1=宵のうち(20-21時) / T2=事件のあった時間帯(21-22時) / T3=夜更け(22-23時)
// カード本文・ハンドアウト・結果画面など、プレイヤーの目に触れる全テキストで使う。
export function naturalizeTime(text: string): string {
  return text
    // T2 系（長いパターンから順に）
    .replace(/T2より前/g, '事件の少し前')
    .replace(/T2前後/g, '事件の前後')
    .replace(/T2の直前/g, '犯行の直前')
    .replace(/T2前/g, '犯行の直前')
    .replace(/T2(の時間帯|の時刻|の頃|頃)/g, '事件のあった時間帯')
    .replace(/T2/g, '事件のあった時間帯')
    // T1 系
    .replace(/T1より前/g, '日暮れ前')
    .replace(/T1(の時間帯|の時刻|の頃|頃)/g, '宵のうち')
    .replace(/T1/g, '宵のうち')
    // T3 系
    .replace(/T3(の時間帯|の時刻|の頃|頃)/g, '夜更け')
    .replace(/T3/g, '夜更け')
}

